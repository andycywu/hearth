#!/bin/sh
# Install `hearth` as a command on a Linux box (a Pi, a set-top box): build this checkout and put a launcher
# called `hearth` in ~/.local/bin, so that after logging in again — over ssh or at the console — `hearth "turn it down"`
# works from any directory.
#
#   sh tools/install.sh              build, install the launcher, say what to do next
#   sh tools/install.sh --no-build   only the launcher (the checkout is already built)
#   sh tools/install.sh --uninstall  remove the launcher (the checkout and ~/.config/hearth stay)
#
# What it touches: ~/.local/bin/hearth (the launcher), one line in ~/.profile if ~/.local/bin is not on PATH yet, and,
# if pnpm is missing, pnpm under ~/.local. No sudo, nothing outside $HOME, nothing fetched at run time.
#
# The launcher puts Node first on PATH (so it works from a non-interactive `ssh host hearth …`, which does not read
# ~/.profile), reads ~/.config/hearth/env into the process if it is there — that is where TV_AGENT_API_KEY and the
# MODELPILOT_* keys live (mode 0600), so a key never appears on a command line — and runs this checkout's build.
set -eu

MODE=install
BUILD=1
for arg in "$@"; do
  case "$arg" in
    --no-build) BUILD=0 ;;
    --uninstall) MODE=uninstall ;;
    -h|--help) sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "install.sh: unknown option $arg (try --help)" >&2; exit 2 ;;
  esac
done

REPO=$(cd "$(dirname "$0")/.." && pwd)
BIN="${HEARTH_BIN_DIR:-$HOME/.local/bin}"
LAUNCHER="$BIN/hearth"
MARK="# generated by tools/install.sh"

if [ "$MODE" = uninstall ]; then
  if [ -f "$LAUNCHER" ] && grep -q "$MARK" "$LAUNCHER"; then
    rm -f "$LAUNCHER"; echo "removed $LAUNCHER"
  else
    echo "no hearth launcher of ours at $LAUNCHER — nothing removed"
  fi
  exit 0
fi

# ---- Node >= 26, found the way the launcher will find it -------------------------------------------------------
NODE_DIR=""
for candidate in "$(command -v node 2>/dev/null || true)" "$HOME/.local/node/bin/node"; do
  [ -n "$candidate" ] && [ -x "$candidate" ] || continue
  major=$("$candidate" -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)
  if [ "$major" -ge 26 ] 2>/dev/null; then NODE_DIR=$(dirname "$candidate"); break; fi
done
if [ -z "$NODE_DIR" ]; then
  echo "install.sh: Node 26 or newer is needed and was not found (looked on PATH and in ~/.local/node/bin)." >&2
  echo "  Unpack the linux-arm64 (Pi) or linux-x64 tarball from https://nodejs.org/dist/ under ~/.local/node and run this again." >&2
  exit 1
fi
echo "node: $NODE_DIR/node ($("$NODE_DIR/node" --version))"

# ---- build ---------------------------------------------------------------------------------------------------
if [ "$BUILD" = 1 ]; then
  export PATH="$NODE_DIR:$HOME/.local/bin:$PATH"
  if ! command -v pnpm >/dev/null 2>&1; then
    echo "pnpm: not found, installing pnpm@9.12.0 under ~/.local (no sudo)"
    npm install -g --prefix "$HOME/.local" pnpm@9.12.0
  fi
  cd "$REPO"
  pnpm install --frozen-lockfile
  pnpm build
fi
if [ ! -f "$REPO/apps/cli/dist/main.js" ]; then
  echo "install.sh: $REPO/apps/cli/dist/main.js does not exist — run without --no-build" >&2
  exit 1
fi

# ---- the launcher ----------------------------------------------------------------------------------------------
mkdir -p "$BIN"
cat > "$LAUNCHER" <<EOF
#!/bin/sh
$MARK — re-run it after moving the checkout. Remove with: sh tools/install.sh --uninstall
export PATH="$NODE_DIR:\$PATH"
HEARTH_ENV="\${XDG_CONFIG_HOME:-\$HOME/.config}/hearth/env"
if [ -r "\$HEARTH_ENV" ]; then set -a; . "\$HEARTH_ENV"; set +a; fi
exec node "$REPO/apps/cli/dist/main.js" "\$@"
EOF
chmod 755 "$LAUNCHER"
echo "launcher: $LAUNCHER -> $REPO/apps/cli/dist/main.js"

# ---- PATH --------------------------------------------------------------------------------------------------------
case ":$PATH:" in
  *":$BIN:"*) ON_PATH=1 ;;
  *) ON_PATH=0 ;;
esac
if [ "$ON_PATH" = 0 ] && [ -z "${HEARTH_NO_PROFILE:-}" ]; then
  LINE="export PATH=\"$BIN:\$PATH\"   # hearth"
  if ! grep -qsF "# hearth" "$HOME/.profile" 2>/dev/null; then
    printf '\n%s\n' "$LINE" >> "$HOME/.profile"
    echo "PATH: added $BIN to ~/.profile"
  fi
fi

echo
echo "Done. $("$LAUNCHER" --version 2>/dev/null | sed 's/^/hearth /')"
if [ "$ON_PATH" = 0 ]; then
  echo "This shell does not have it on PATH yet. Either log out and in (ssh again), or run:"
  echo "  . ~/.profile"
fi
echo
echo "Next:"
echo "  hearth --platform linux setup        # look at this box, remember the result (run once)"
echo "  hearth modelpilot status             # are the ModelPilot services reachable, and is the key accepted"
echo "  hearth \"turn it down\"                # after setup, no flags"
