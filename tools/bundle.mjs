#!/usr/bin/env node
/**
 * Bundles the agent runtime for a device target using esbuild.
 *
 *   node tools/bundle.mjs <tizen|aosp|webos|dev> [--watch] [--dev]
 *                         [--with a,b] [--without c] [--full]
 *
 * Each target has an entry file that wires the core to the right platform
 * adapter and LLM connector. The output is a single ESM `main.js` (plus
 * sourcemap) dropped where the app host loads it. Run `pnpm build` first so the
 * workspace packages' dist/ exists for esbuild to resolve.
 *
 * ## Why there are feature flags
 *
 * The default build is what a working television needs and nothing else. The
 * bring-up tooling, the offline scripted brain, the on-screen keyboard and the
 * demo script are all real and all optional, and each one that ships by default
 * is parse time charged to every launch on every set.
 *
 *   node tools/bundle.mjs aosp                      # default profile
 *   node tools/bundle.mjs aosp --with diag,demo     # add bring-up bits
 *   node tools/bundle.mjs aosp --without modelpilot # a runtime with no service
 *   node tools/bundle.mjs aosp --full               # everything, for the bench
 *
 * Build-time rather than `await import()` on purpose: TV WebViews run a
 * Chromium the set shipped with, dynamic import is not guaranteed on the older
 * ones, and a second file to fetch is a second thing that can fail on a device
 * with no console. One file, decided before it leaves the build machine.
 *
 * See packages/core/src/features.ts for how a guard has to be written.
 */
import { build, context } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TARGETS = {
  tizen: {
    entry: "apps/tizen-app/src/main.ts",
    outfile: "apps/tizen-app/main.js",
  },
  aosp: {
    entry: "apps/aosp-app/web/main.ts",
    outfile: "apps/aosp-app/app/src/main/assets/main.js",
  },
  webos: {
    entry: "apps/webos-app/src/main.ts",
    outfile: "apps/webos-app/main.js",
  },
  dev: {
    entry: "apps/dev-harness/src/main.ts",
    outfile: "apps/dev-harness/main.js",
  },
};

/**
 * What a television gets unless somebody says otherwise.
 *
 * `modelpilot` is on because it is how the runtime reaches the service, and it
 * stays inert without a credential. `avatar` is on because it is the thing a
 * viewer actually looks at. The other four are tools for whoever is holding the
 * remote during bring-up, and they are off.
 */
const DEFAULT_FEATURES = {
  diag: false,
  offline: false,
  modelpilot: true,
  avatar: true,
  keyboard: false,
  demo: false,
};

const args = process.argv.slice(2);
const target = args[0];
const watch = args.includes("--watch");
const dev = args.includes("--dev");
const cfg = TARGETS[target];
if (!cfg) {
  console.error(
    "Usage: node tools/bundle.mjs <tizen|aosp|webos|dev> [--watch] [--dev]\n" +
    "                             [--with a,b] [--without c] [--full]\n" +
    `  features: ${Object.keys(DEFAULT_FEATURES).join(", ")}`,
  );
  process.exit(1);
}

/** Repeatable and comma-separated, like the Tizen packager's `--flags`. */
function listOpt(name) {
  return args.reduce(
    (acc, a, i) => (a === name && args[i + 1] ? [...acc, ...args[i + 1].split(",")] : acc), [],
  ).map((f) => f.trim()).filter(Boolean);
}

const features = { ...DEFAULT_FEATURES };
// The dev harness is the bench. It is not installed on anything and nobody
// waits for it to parse, so it carries the lot unless told not to.
if (dev || target === "dev" || args.includes("--full")) {
  for (const k of Object.keys(features)) features[k] = true;
}
for (const f of listOpt("--with")) setFeature(f, true);
for (const f of listOpt("--without")) setFeature(f, false);

function setFeature(name, on) {
  if (!(name in DEFAULT_FEATURES)) {
    console.error(
      `[bundle] unknown feature "${name}". Known: ${Object.keys(DEFAULT_FEATURES).join(", ")}`,
    );
    process.exit(1);
  }
  features[name] = on;
}

/** `diag` -> `__HEARTH_DIAG__`, the identifier the guards are written against. */
const define = Object.fromEntries(
  Object.entries(features).map(([k, v]) => [`__HEARTH_${k.toUpperCase()}__`, String(v)]),
);

/** @type {import('esbuild').BuildOptions} */
const options = {
  entryPoints: [resolve(root, cfg.entry)],
  outfile: resolve(root, cfg.outfile),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2020"],            // conservative baseline for TV Chromium/Blink
  minify: !dev,
  sourcemap: true,
  legalComments: "none",
  logLevel: "info",
  define,
  banner: { js: "/* TV AI Agent runtime — generated by tools/bundle.mjs. Do not edit. */" },
};

if (watch) {
  const ctx = await context(options);
  await ctx.watch();
  console.log(`[bundle] watching ${target} → ${cfg.outfile}`);
} else {
  const result = await build({ ...options, metafile: true });
  const out = Object.values(result.metafile.outputs).find((o) => o.entryPoint);
  const on = Object.entries(features).filter(([, v]) => v).map(([k]) => k);
  console.log(
    `[bundle] built ${target} → ${cfg.outfile}` +
    (out ? ` (${(out.bytes / 1024).toFixed(1)} KB)` : "") +
    `\n[bundle] features: ${on.length ? on.join(" ") : "minimal"}`,
  );
}
